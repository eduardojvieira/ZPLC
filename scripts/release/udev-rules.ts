// The udev rule that the .deb and the .rpm install (REL-013), written from the files that already say which USB
// devices are ZPLC boards, so that it cannot drift from them:
//
//   bun scripts/release/udev-rules.ts --out packages/zplc-ide/build/linux/70-zplc-boards.rules
//
// tools/hil/usb-ids.json holds the vendor and product identifiers that a build or a bench run showed, keyed by the
// ide_id of firmware/app/boards/boards.json. The rule tags each of those serial devices `uaccess`, which makes
// systemd-logind give an access control entry to the user who is logged in at the machine, and sets
// ID_MM_DEVICE_IGNORE so that ModemManager does not probe a PLC as a modem. A board with no recorded identifier gets
// no rule (a rule that matched every ACM device would reach far more than the supported boards): the file says so and
// the install page gives the group fallback.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

export interface UsbId { vid: string; pid: string; source: string }
export type UsbIds = Record<string, { ids: UsbId[]; note?: string }>;
export interface BoardEntry { ide_id: string; display_name: string }

/** Before 70-uaccess.rules and 73-seat-late.rules, where systemd acts on the tag. */
export const RULE_FILE_NAME = '70-zplc-boards.rules';
/** The vendor folder of rules; /lib and /usr/lib are the same place on every distribution that has the merged /usr. */
export const RULE_TARGET = `/usr/lib/udev/rules.d/${RULE_FILE_NAME}`;

const ROOT = resolve(import.meta.dir, '..', '..');
const HEX4 = /^[0-9a-fA-F]{4}$/;

export function readUsbIds(path = join(ROOT, 'tools/hil/usb-ids.json')): UsbIds {
  const parsed = JSON.parse(readFileSync(path, 'utf8')) as { boards: Record<string, { ids?: UsbId[]; note?: string }> };
  return Object.fromEntries(Object.entries(parsed.boards).map(([board, entry]) => [board, { ids: entry.ids ?? [], ...(entry.note === undefined ? {} : { note: entry.note }) }]));
}

export function renderUdevRules(usbIds: UsbIds, boards: BoardEntry[]): string {
  const names = new Map(boards.map((board) => [board.ide_id, `${board.display_name} (${board.ide_id})`]));
  const pairs = new Map<string, { vid: string; pid: string; boards: string[] }>();
  for (const [board, entry] of Object.entries(usbIds)) {
    const name = names.get(board);
    if (name === undefined) throw new Error(`usb-ids.json names the board ${board}, which firmware/app/boards/boards.json does not have`);
    for (const id of entry.ids) {
      if (!HEX4.test(id.vid)) throw new Error(`${board}: vendor identifier ${JSON.stringify(id.vid)} is not four hexadecimal digits`);
      if (!HEX4.test(id.pid)) throw new Error(`${board}: product identifier ${JSON.stringify(id.pid)} is not four hexadecimal digits`);
      const key = `${id.vid.toLowerCase()}:${id.pid.toLowerCase()}`;
      const found = pairs.get(key) ?? { vid: id.vid.toLowerCase(), pid: id.pid.toLowerCase(), boards: [] };
      if (!found.boards.includes(name)) found.boards.push(name);
      pairs.set(key, found);
    }
  }
  const lines = [
    '# ZPLC boards: the user who is logged in at this machine may open the USB serial port of a board (REL-013).',
    '# GENERATED by scripts/release/udev-rules.ts from tools/hil/usb-ids.json and firmware/app/boards/boards.json. Do not edit.',
    '#',
    '# uaccess: systemd-logind gives the user of the active session an access control entry on the device, and removes',
    '# it when the session ends, so no group membership and no reboot are needed. ID_MM_DEVICE_IGNORE keeps ModemManager',
    '# from probing the board as a modem.',
    '',
  ];
  for (const { vid, pid, boards: users } of [...pairs.values()].sort((a, b) => `${a.vid}:${a.pid}`.localeCompare(`${b.vid}:${b.pid}`))) {
    lines.push(`# ${vid}:${pid}: ${users.join(', ')}`);
    lines.push(`SUBSYSTEM=="tty", SUBSYSTEMS=="usb", ATTRS{idVendor}=="${vid}", ATTRS{idProduct}=="${pid}", TAG+="uaccess", ENV{ID_MM_DEVICE_IGNORE}="1"`);
    lines.push('');
  }
  const uncovered = boards.filter((board) => !(usbIds[board.ide_id]?.ids.length));
  if (uncovered.length > 0) {
    lines.push('# No rule below for these boards: their serial port is on a USB bridge whose identifiers depend on the board', '# revision, or the board has no recorded identifier. Add the user to the serial group instead (dialout on Debian,', '# Ubuntu and Fedora, uucp on Arch):');
    for (const board of uncovered) lines.push(`# ${board.display_name} (${board.ide_id}): no USB identifier is recorded`);
    lines.push('');
  }
  return `${lines.join('\n')}`;
}

if (import.meta.main) {
  const flag = Bun.argv.indexOf('--out');
  const out = flag > -1 ? Bun.argv[flag + 1] : undefined;
  if (!out) {
    console.error('usage: bun scripts/release/udev-rules.ts --out <file>');
    process.exit(2);
  }
  const boards = JSON.parse(readFileSync(join(ROOT, 'firmware/app/boards/boards.json'), 'utf8')) as BoardEntry[];
  mkdirSync(dirname(resolve(out)), { recursive: true });
  writeFileSync(out, renderUdevRules(readUsbIds(), boards));
  console.log(`udev-rules: wrote ${out}`);
}
