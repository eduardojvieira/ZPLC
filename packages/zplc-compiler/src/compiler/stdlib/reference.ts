const pin = (name: string, type: string, en: string, es: string, initial?: string): PinDoc => ({ name, type, en, es, ...(initial ? { initial } : {}) });

const block = (
    category: string,
    pins: PinDoc[],
    en: string,
    es: string,
    source: string,
    expect: string,
    more: Partial<Pick<Example, 'scans' | 'scanMs'>> = {},
): BlockDoc => ({
    category, pins, en, es,
    example: { source: source.trim(), expect, ...(more.scans ? { scans: more.scans } : {}), ...(more.scanMs ? { scanMs: more.scanMs } : {}) },
});

const TIMER_PINS = (inEn: string, inEs: string, qEn: string, qEs: string, etEn: string, etEs: string): PinDoc[] => [
    pin('IN', 'BOOL', inEn, inEs),
    pin('PT', 'TIME', 'Preset time.', 'Tiempo preseleccionado.'),
    pin('Q', 'BOOL', qEn, qEs),
    pin('ET', 'TIME', etEn, etEs),
];

