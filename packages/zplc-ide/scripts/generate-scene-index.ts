// Writes src/generated/sceneIndex.ts from plant-scenes/<id>/scene.json (S2).
//   bun scripts/generate-scene-index.ts           write the index
//   bun scripts/generate-scene-index.ts --check   fail when the index is out of date with plant-scenes/
// An absent or empty plant-scenes/ gives an empty index.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SCENES = join(ROOT, 'plant-scenes');
const OUT = join(ROOT, 'src/generated/sceneIndex.ts');
const FILES = ['scene.json', 'plant-map.json', 'reference.st', 'starter.st', 'scenario.json'];

// The shipped scenes in the order of difficulty of spec 012's table of reference scenes (its scene numbers), so the chooser lists
// them in that order and the plant document opens scene 1 first. A new scene is added here with its number.
const SCENE_ORDER: Record<string, number> = {
  'belt-to-sensor': 1,
  'latch-two-sensors': 2,
  'timed-tank': 3,
  'counted-queue': 4,
  'two-axis-assembly': 5,
  'two-axis-assembly-numeric': 6,
  'buffer-release': 8,
  'merge-lines': 9,
  'tank-level-control': 12,
  'layer-palletizer': 13,
  'belt-to-belt-transfer': 14,
  'three-axis-palletizing': 15,
};

function generate(): { problems: string[]; source: string } {
  const problems: string[] = [];
  const entries: { id: string; dir: string; names: { en: string; es: string } }[] = [];
  const ids = existsSync(SCENES)
    ? readdirSync(SCENES)
        .filter((id) => statSync(join(SCENES, id)).isDirectory())
        .sort((a, b) => (SCENE_ORDER[a] ?? Infinity) - (SCENE_ORDER[b] ?? Infinity) || a.localeCompare(b))
    : [];
  for (const id of ids)
    if (!(id in SCENE_ORDER)) problems.push(`plant-scenes/${id}: add it to SCENE_ORDER in scripts/generate-scene-index.ts`);
  for (const id of ids) {
    const missing = FILES.filter((file) => !existsSync(join(SCENES, id, file)));
    if (missing.length > 0) {
      problems.push(`plant-scenes/${id}: missing ${missing.join(', ')}`);
      continue;
    }
    // ponytail: scene.json has no per-language name yet, so both languages carry its name; add a names source with the course texts
    const { name } = JSON.parse(readFileSync(join(SCENES, id, 'scene.json'), 'utf8')) as { name?: unknown };
    if (typeof name !== 'string' || name.length === 0) problems.push(`plant-scenes/${id}/scene.json: needs a name`);
    else entries.push({ id, dir: `plant-scenes/${id}`, names: { en: name, es: name } });
  }
  const source = [
    '// GENERATED by scripts/generate-scene-index.ts from packages/zplc-ide/plant-scenes/*/. Do not edit.',
    '// `bun scripts/generate-scene-index.ts --check` fails when this file is out of date with the shipped scenes.',
    '',
    `export const SCENE_INDEX: readonly { id: string; dir: string; names: { en: string; es: string } }[] ` +
      `= ${JSON.stringify(entries, null, 2)};`,
    '',
  ].join('\n');
  return { problems, source };
}

function main(): number {
  const { values } = parseArgs({ options: { check: { type: 'boolean' } }, strict: true });
  const { problems, source } = generate();
  if (problems.length > 0) {
    for (const problem of problems) console.error(`scene index: ${problem}`);
    return 1;
  }
  const current = existsSync(OUT) && readFileSync(OUT, 'utf8') === source;
  if (values.check) {
    if (current) console.log('scene index is current');
    else console.error(`${relative(ROOT, OUT)} out of date with plant-scenes/: run \`bun run generate:scene-index\``);
    return current ? 0 : 1;
  }
  if (!current) writeFileSync(OUT, source);
  console.log(current ? 'scene index already current' : `written: ${relative(ROOT, OUT)}`);
  return 0;
}

process.exit(main());
