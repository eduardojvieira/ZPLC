/**
 * Renders the token table of `tokens.ts` as the stylesheet the application loads (`tokens.generated.css`). Pure string
 * work, so the generator in tools/ci/ux-tokens.ts and the tests share it.
 *
 * The cascade it produces, from lowest to highest:
 *   :root                         the light theme, every token (the default, and the base of the others)
 *   :root.dark                    the tokens whose dark value differs
 *   @media (prefers-color-scheme: dark) :root:not(.light):not(.dark):not(.high-contrast)
 *                                 the same overrides when the system chose dark and the user chose nothing; a user's
 *                                 explicit high-contrast choice is never overridden by the system preference
 *   :root.high-contrast           the tokens whose high-contrast value differs, last so it wins
 *   html[data-density=compact]    the density overrides
 */
import { TOKENS, type ThemeId, type TokenDef } from './tokens';

export const GENERATED_HEADER = `/* GENERATED by tools/ci/ux-tokens.ts from src/theme/tokens.ts. Do not edit by hand: change the token source and run
   \`bun tools/ci/ux-tokens.ts --write\`. CI fails when this file differs from what the source renders (UX-003). */`;

const SCHEME: Record<ThemeId, 'light' | 'dark'> = { light: 'light', dark: 'dark', 'high-contrast': 'dark' };

function block(selector: string, lines: string[], indent = ''): string[] {
  return [`${indent}${selector} {`, ...lines.map((line) => `${indent}  ${line}`), `${indent}}`];
}

/** The `--name: value;` lines of the tokens a theme overrides, with a comment per group. */
function overrides(theme: ThemeId): string[] {
  const out: string[] = [];
  let group = '';
  for (const def of TOKENS) {
    if (def[theme] === def.light) continue;
    if (def.group !== group) { group = def.group; out.push(`/* ${group} */`); }
    out.push(`${def.name}: ${def[theme]};`);
  }
  return out;
}

function everything(): string[] {
  const out: string[] = [];
  let group = '';
  let tier = '';
  for (const def of TOKENS) {
    if (def.tier !== tier) { tier = def.tier; out.push(`/* ${TIER_TITLE[def.tier]} */`); group = ''; }
    if (def.group !== group) { group = def.group; out.push(`/* ${group} */`); }
    out.push(`${def.name}: ${def.light};`);
  }
  return out;
}

const TIER_TITLE: Record<TokenDef['tier'], string> = {
  ramp: 'Tier 1: colour ramps (raw values; only roles name them)',
  role: 'Tier 2: semantic roles (light theme; the other themes override them below)',
  component: 'Tier 3: component tokens (they read roles, so they follow every theme)',
  scale: 'Scales: type, shape, elevation, icons, layers and density',
};

export function renderTokensCss(): string {
  const dark = overrides('dark');
  const compact = TOKENS.filter((def) => def.compact !== undefined).map((def) => `${def.name}: ${def.compact};`);
  const css = [
    GENERATED_HEADER,
    '',
    ...block(':root', ['color-scheme: light;', ...everything()]),
    '',
    ...block(':root.dark', [`color-scheme: ${SCHEME.dark};`, ...dark]),
    '',
    '@media (prefers-color-scheme: dark) {',
    ...block(':root:not(.light):not(.dark):not(.high-contrast)', [`color-scheme: ${SCHEME.dark};`, ...dark], '  '),
    '}',
    '',
    ...block(':root.high-contrast', [`color-scheme: ${SCHEME['high-contrast']};`, ...overrides('high-contrast')]),
    '',
    ...block('html[data-density="compact"]', compact),
    '',
    '/* Forced colours: the operating system supplies the focus colour. */',
    '@media (forced-colors: active) {',
    ...block(':root', ['--focus-ring-color: Highlight;'], '  '),
    '}',
    '',
  ];
  return css.join('\n');
}
