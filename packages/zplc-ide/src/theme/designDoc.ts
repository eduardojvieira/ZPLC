/** DESIGN.md with its front matter and token region replaced by what the token source renders. */
export function applyGeneratedParts(document: string): string {
  const body = document.replace(/^---\n[\s\S]*?\n---\n/, '');
  const begin = body.indexOf(TABLES_BEGIN);
  const end = body.indexOf(TABLES_END);
  if (begin < 0 || end < begin) throw new Error(`DESIGN.md needs the markers ${TABLES_BEGIN} and ${TABLES_END}`);
  const region = `${TABLES_BEGIN}\n\n${renderTokenTables()}\n${TABLES_END}`;
  return `${renderFrontMatter()}${body.slice(0, begin)}${region}${body.slice(end + TABLES_END.length)}`;
}
