#!/usr/bin/env python3
"""Write a libFuzzer dictionary of the container constants, from tools/contract/contract.json (VF-014).

    python3 tools/fuzz/make_dict.py > zplc.dict

Nothing is copied by hand: magic, version, segment types, flags, task types, tag ids, data types, memory
bases and sizes, system registers, communication kinds and every opcode come from the contract table, so a
new opcode or segment type reaches the fuzzers by regenerating the dictionary.
"""
import json
import struct
import sys
from pathlib import Path

CONTRACT = Path(__file__).resolve().parents[1] / "contract" / "contract.json"


def number(value):
    return int(value, 0) if isinstance(value, str) else int(value)


def token(raw):
    return '"' + "".join("\\x%02X" % byte for byte in raw) + '"'


def main():
    contract = json.loads(CONTRACT.read_text())
    entries = {}

    def add(name, raw):
        entries[name] = raw

    container = contract["container"]
    add("magic", struct.pack("<I", number(container["magic"]["value"])))
    add("version", struct.pack("<HH", contract["abi"]["versionMajor"], contract["abi"]["versionMinor"]))
    enums = {e["name"]: e for e in container["enums"]}
    for member in enums["segmentTypes"]["members"]:
        add("segment_" + member["name"].lower(), struct.pack("<H", number(member["value"])))
    for member in enums["fileFlags"]["members"]:
        add("flag_" + member["name"].lower(), struct.pack("<I", 1 << number(member["value"])))
    for member in enums["taskTypes"]["members"]:
        add("task_type_" + member["name"].lower(), struct.pack("<B", number(member["value"])))
    for member in enums["tagIds"]["members"]:
        add("tag_" + member["name"].lower(), struct.pack("<B", number(member["value"])))
    for member in contract["types"]["members"]:
        add("type_" + member["name"].lower(), struct.pack("<B", number(member["value"])))
    for region in contract["memory"]["regions"]:
        add("base_" + region["name"].lower(), struct.pack("<H", number(region["base"])))
        add("end_" + region["name"].lower(), struct.pack("<H", number(region["base"]) + number(region["size"]) - 1))
    for register in contract["memory"]["systemRegisters"]:
        add("sysreg_" + register["macro"].lower(), struct.pack("<H", number(register["offset"])))
    limits = {limit["macro"]: limit["value"] for limit in contract["memory"]["limits"]}
    add("stack_depth", struct.pack("<H", limits["ZPLC_STACK_MAX_DEPTH"]))
    add("max_tasks", struct.pack("<H", container["maxTasks"]["value"]))
    for kind in contract["comm"]["kinds"]["members"]:
        value = number(kind["value"])
        add("comm_" + kind["name"].lower(), struct.pack("<I", value))
    add("comm_kind_max", struct.pack("<I", number(contract["comm"]["kindMax"]["value"])
                                    if isinstance(contract["comm"]["kindMax"], dict) else number(contract["comm"]["kindMax"])))
    for opcode in contract["opcodes"]:
        add("op_" + opcode["name"].lower(), struct.pack("<B", number(opcode["code"])))
    # An instruction with an operand of the size its row says: the opcode followed by zeros.
    for opcode in contract["opcodes"]:
        if opcode["operand"] > 0:
            add("insn_" + opcode["name"].lower(), struct.pack("<B", number(opcode["code"])) + bytes(opcode["operand"]))

    print("# Generated by tools/fuzz/make_dict.py from tools/contract/contract.json. Do not edit.")
    for name, raw in entries.items():
        print("%s=%s" % (name, token(raw)))


if __name__ == "__main__":
    sys.exit(main())
