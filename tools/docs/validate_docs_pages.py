#!/usr/bin/env python3
"""Docs page checks (VF-019). Fails on:

1. a page whose last non-empty line is not a complete sentence, table row, list item,
   closing code fence or admonition end (a page cut off mid-sentence);
2. a page that is not in docs/sidebars.js (front matter `unlisted: true` or `draft: true` opts out);
3. an English and Spanish pair whose heading levels or number of code blocks differ.

    python3 tools/docs/validate_docs_pages.py
"""
from __future__ import annotations

from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
EN_DIR = "docs/docs"
ES_DIR = "docs/i18n/es/docusaurus-plugin-content-docs/current"
SIDEBAR = "docs/sidebars.js"

FENCE = re.compile(r"^\s*(`{3,}|~{3,})")
HEADING = re.compile(r"^(#{1,6})\s+\S")
LIST_ITEM = re.compile(r"^\s*([-*+]|\d+[.)])\s+\S")
CLOSERS = "\"')]}*_`”’»"


def pages(root: Path, base: str) -> dict[str, Path]:
    # Docusaurus skips files and folders that start with an underscore.
    return {
        path.relative_to(root / base).as_posix(): path
        for path in sorted((root / base).rglob("*"))
        if path.suffix in {".md", ".mdx"}
        and not any(part.startswith("_") for part in path.relative_to(root / base).parts)
    }


def split_front_matter(text: str) -> tuple[dict[str, str], list[str]]:
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return {}, lines
    for end in range(1, len(lines)):
        if lines[end].strip() == "---":
            meta = {}
            for line in lines[1:end]:
                key, separator, value = line.partition(":")
                if separator:
                    meta[key.strip()] = value.strip()
            return meta, lines[end + 1 :]
    return {}, lines


def scan(lines: list[str]) -> tuple[list[int], int, bool]:
    """Heading levels outside code, number of code blocks, and whether a block is still open at the end."""
    levels: list[int] = []
    blocks = 0
    fence = ""
    for line in lines:
        marker = FENCE.match(line)
        if fence:
            if marker and marker.group(1)[0] == fence[0] and len(marker.group(1)) >= len(fence):
                fence = ""
        elif marker:
            fence = marker.group(1)
            blocks += 1
        elif heading := HEADING.match(line):
            levels.append(len(heading.group(1)))
    return levels, blocks, bool(fence)


def ending_error(text: str) -> str | None:
    lines = text.splitlines()
    non_empty = [line.strip() for line in lines if line.strip()]
    if not non_empty:
        return "page is empty"
    last = non_empty[-1]
    if scan(lines)[2]:
        return f'ends inside a code block, at "{last[-60:]}"'
    if FENCE.match(last) or last == ":::":
        return None
    if (last.startswith("|") and last.endswith("|")) or LIST_ITEM.match(last):
        return None
    if last.rstrip(CLOSERS)[-1:] in {".", "!", "?", "…"} and not HEADING.match(last):
        return None
    return f'ends mid-sentence (the last line is not a complete sentence, table row, list item, code fence or admonition end): "{last[-60:]}"'


def check_endings(root: Path) -> list[str]:
    errors = []
    for prefix, base in (("", EN_DIR), ("es:", ES_DIR)):
        for name, path in pages(root, base).items():
            if message := ending_error(path.read_text()):
                errors.append(f"{prefix}{name}: {message}")
    return errors


def check_sidebar(root: Path) -> list[str]:
    # ponytail: reads every quoted string of sidebars.js as a doc id, so it cannot follow autogenerated
    # sidebars or ids built in code; switch to `node -e` on the evaluated sidebar if sidebars.js grows logic.
    listed = set(re.findall(r"""['"]([A-Za-z0-9_./-]+)['"]""", (root / SIDEBAR).read_text()))
    errors = []
    for prefix, base in (("", EN_DIR), ("es:", ES_DIR)):
        for name, path in pages(root, base).items():
            meta, _ = split_front_matter(path.read_text())
            if meta.get("unlisted") == "true" or meta.get("draft") == "true":
                continue
            folder = Path(name).parent.as_posix()
            doc_id = meta.get("id") or Path(name).stem
            full_id = doc_id if folder == "." else f"{folder}/{doc_id}"
            if full_id not in listed:
                errors.append(f"{prefix}{name}: page is not in the sidebar (add '{full_id}' to {SIDEBAR} or set `unlisted: true`)")
    return errors


def check_parity(root: Path) -> list[str]:
    spanish = pages(root, ES_DIR)
    errors = []
    for name, path in pages(root, EN_DIR).items():
        if name not in spanish:
            continue  # not a pair
        en_levels, en_blocks, _ = scan(split_front_matter(path.read_text())[1])
        es_levels, es_blocks, _ = scan(split_front_matter(spanish[name].read_text())[1])
        if en_levels != es_levels:
            errors.append(f"{name}: heading structure differs, EN {en_levels} and ES {es_levels}")
        if en_blocks != es_blocks:
            errors.append(f"{name}: number of code blocks differs, EN {en_blocks} and ES {es_blocks}")
    return errors


def validate(root: Path = ROOT) -> list[str]:
    return check_endings(root) + check_sidebar(root) + check_parity(root)


def main() -> int:
    errors = validate()
    for error in errors:
        print(f"ERROR: {error}")
    if errors:
        return 1
    print(
        f"Validated page endings, sidebar membership and EN/ES shape for "
        f"{len(pages(ROOT, EN_DIR))} English and {len(pages(ROOT, ES_DIR))} Spanish pages"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
