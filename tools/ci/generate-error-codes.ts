// Generates the list of error codes that the main process of Studio reads (CMP-006).
//
//   bun tools/ci/generate-error-codes.ts           write packages/zplc-ide/electron/errorCodes.generated.ts
//   bun tools/ci/generate-error-codes.ts --check   fail when that file is not what the registry produces
//
// The one list of the codes of a failed build is packages/zplc-compiler/src/compiler/error-codes.ts. The compiler, the
// Tool API, the CLI, the MCP server and the renderer of Studio read it from the package. The main process is compiled
// apart from the rest of Studio (tsconfig.electron.json has `rootDir: electron`) and does not load the compiler, so it
// reads this copy, which a failing check keeps equal.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

import { ERROR_CODES } from '../../packages/zplc-compiler/src/compiler/error-codes';

const ROOT = resolve(import.meta.dir, '../..');
export const MIRROR_FILE = join(ROOT, 'packages/zplc-ide/electron/errorCodes.generated.ts');

/** The text of the generated module. */
export function renderMirror(codes: readonly string[] = ERROR_CODES): string {
  return [
    '// GENERATED by tools/ci/generate-error-codes.ts from packages/zplc-compiler/src/compiler/error-codes.ts. Do not edit:',
    '// change the registry and run `bun tools/ci/generate-error-codes.ts`.',
    '',
    '/** The codes of the errors of a build (CMP-006), in the order of the registry. */',
    'export const ERROR_CODE_MIRROR: readonly string[] = [',
    ...codes.map((code) => `  '${code}',`),
    '];',
    '',
    'const KNOWN: ReadonlySet<string> = new Set(ERROR_CODE_MIRROR);',
    '',
    'export function isMirroredErrorCode(value: unknown): boolean {',
    "  return typeof value === 'string' && KNOWN.has(value);",
    '}',
    '',
  ].join('\n');
}

function main(): number {
  const wanted = renderMirror();
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(MIRROR_FILE, 'utf8'); } catch { /* missing */ }
    if (current === wanted) return 0;
    console.error(`${MIRROR_FILE} is not what the registry of error codes produces: run bun tools/ci/generate-error-codes.ts`);
    return 1;
  }
  writeFileSync(MIRROR_FILE, wanted);
  console.log(`wrote ${MIRROR_FILE}`);
  return 0;
}

if (import.meta.main) process.exit(main());
