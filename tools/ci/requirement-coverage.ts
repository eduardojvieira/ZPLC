// Which requirements of the 2.0 remediation have an executed check (spec section 8 gate 2, plan section 10).
//
//   bun tools/ci/requirement-coverage.ts                 counts per workstream and overall
//   bun tools/ci/requirement-coverage.ts --list          also the requirements without a passing check, with their titles
//   bun tools/ci/requirement-coverage.ts --groups        the owning packages with the most requirements still to cover (--top N; 20)
//   bun tools/ci/requirement-coverage.ts --json          everything as JSON
//   bun tools/ci/requirement-coverage.ts --write         rewrite tools/ci/requirement-evidence.json from the tracked tree
//   bun tools/ci/requirement-coverage.ts --check         CI: fail when that file is not what --write would produce
//
// A check names its requirement in its own metadata, so adding a check needs no edit to a registry:
//   conformance  the "requirement" of a conformance/**/*.expect.json (VF-002)
//   unit         the title of a describe, it or test of a test file that a CI job runs, e.g. describe('session store (IDE-008)')
//   unit         also the title of a describeCases table of packages/zplc-hil/tests, e.g. describeCases('HIL cases (HIL-001)', cases)
//   c-test       a comment of a firmware test file, e.g. /* ---- RT-017: resume continues the scan ---- */
//   py-test      a comment line of a Python file that a CI workflow command runs, e.g. # ---- HIL-015: what it proves ----
//                (the files come from the commands in .github/workflows: `python3 path.py` and `unittest discover -s DIR -p GLOB`)
//   journey      the `proves` and `partly` lists of a journey in packages/zplc-ide/scripts/journeys.ts
// A title with "stopgap" covers only a leg of the requirement, and so does a journey's `partly`.
// Records that a person writes (a manual run, a hardware record, or a note that says why a scanned check proves less)
// live in tools/ci/requirement-evidence.json with a "note" and survive --write; everything else there is scanned.
// A `decided` record is one of them: a requirement that a decision of the spec makes conditional, and whose default
// asks for no work (IO-016 under D-06's default B). It has its own column and is never counted as covered by a check.
// A `gate` record is one too: its note names the evidence that no test can give (a run on a physical board, a hardware
// record, a hosted CI run, a study with people, a decision of the owner). While a requirement has one it is at most partial,
// whatever its checks say, so that a new test that names it cannot turn it covered; --list prints the note.
//
// A requirement is covered when at least one of its checks is not partial and is not on the expected-failure list
// (tools/ci/expected-failures.json): with the CI rule that any other failure turns the job red, "not listed" is "passing".
// It is partial when it has checks but none of them qualifies (or a gate holds it), decided when its only record is a
// decision, and uncovered when it has none (a gate is not a check).
import { readFileSync, writeFileSync } from 'node:fs';
import { parseArgs } from 'node:util';

import { ID_PATTERN, validateIndex, type Requirement } from './generate-requirement-index';
import { TEST_FILE, type Inventory } from './test-inventory';
import { flattenConcatenations } from './source-text';

export type Kind = 'conformance' | 'unit' | 'journey' | 'c-test' | 'manual' | 'hardware' | 'py-test' | 'decided' | 'gate';
export interface Check {
  kind: Kind;
  /** Repository-relative file that holds the check (or, for manual and hardware, its record). */
  ref: string;
  /** The stable name of the check inside `ref`; the file must contain it. */
  test?: string;
  /** The check proves one leg of the requirement (a stopgap, a part of a journey). */
  partial?: boolean;
  /** Written by a person: why this record exists. Records without a note are regenerated by --write. */
  note?: string;
}
export type Evidence = Record<string, Check[]>;
export type State = 'covered' | 'partial' | 'decided' | 'uncovered';
export interface Counts { total: number; covered: number; partial: number; decided: number; uncovered: number }

export const KINDS: Kind[] = ['conformance', 'unit', 'journey', 'c-test', 'manual', 'hardware', 'py-test', 'decided', 'gate'];
const CONFORMANCE_RUNNER = 'packages/zplc-ide/src/conformance/conformance.test.ts';
const JOURNEYS = 'packages/zplc-ide/scripts/journeys.ts';
const RUN_JOURNEYS = 'packages/zplc-ide/scripts/run-journeys.ts';
const ROOT = new URL('../../', import.meta.url);
export const EVIDENCE_FILE = new URL('tools/ci/requirement-evidence.json', ROOT);
const IDS = /\b[A-Z]{2,4}-[0-9]{3}\b/g;
const idsOf = (text: string) => [...new Set(text.match(IDS) ?? [])];

// ---------------------------------------------------------------------------------------------------------------------
// Finding checks
// ---------------------------------------------------------------------------------------------------------------------

export function conformanceChecks(path: string, text: string): Array<[string, Check]> {
  const { requirement, title } = JSON.parse(text) as { requirement?: unknown; title?: unknown };
  if (typeof requirement !== 'string' || !ID_PATTERN.test(requirement) || typeof title !== 'string') throw new Error(`${path}: an expectation needs a requirement like CMP-011 and a title`);
  return [[requirement, { kind: 'conformance', ref: path, test: `${requirement} ${title}` }]];
}

// itNative is the test of a file that needs the native runtime (src/cli/nativeRuntimeGuard.ts), and itWasm the one of a file
// that needs the WebAssembly runtime (src/cli/wasmModuleGuard.ts): each skips locally and fails in CI when what it needs is
// missing, so a title of either is a check that CI executes.
// ponytail: a regex over the source, not a parser. A call counts when it starts its line, so a test source held in a string
// (a fixture) is not mistaken for a test; a name built at run time (a template with ${}) and it.each names are not found.
const TITLE = /^[ \t]*(?:describe|describeCases|it|itNative|itWasm|test)(?:\.(?:only|concurrent))?\(\s*(['"`])((?:\\.|(?!\1)[^\\])*)\1/gm;


export function unitChecks(ref: string, source: string): Array<[string, Check]> {
  const found: Array<[string, Check]> = [];
  for (const [, , title = ''] of flattenConcatenations(source).matchAll(TITLE)) {
    if (title.includes('${')) continue;
    for (const id of idsOf(title)) found.push([id, { kind: 'unit', ref, test: title, ...(/\bstopgap\b/i.test(title) && { partial: true }) }]);
  }
  return found;
}

export function cChecks(ref: string, text: string): Array<[string, Check]> {
  const found: Array<[string, Check]> = [];
  for (const line of text.split('\n')) {
    if (!/^\s*(\/\*|\*|\/\/)/.test(line)) continue;
    const comment = line.replace(/^\s*(\/\*+|\*+|\/\/)\s*/, '').replace(/\s*\*\/\s*$/, '').replace(/^-+\s*|\s*-+$/g, '').replace(/^@\w+\s+/, '').trim();
    for (const id of idsOf(comment)) found.push([id, { kind: 'c-test', ref, test: comment }]);
  }
  return found;
}

/** The `# ---- ID: what it proves ----` comment lines of a Python test, the convention of the C tests. */
export function pythonChecks(ref: string, text: string): Array<[string, Check]> {
  const found: Array<[string, Check]> = [];
  for (const [, comment = ''] of text.matchAll(/^[ \t]*#[ \t]*-{4}[ \t]*(.*?)[ \t]*-{4}[ \t]*$/gm)) {
    for (const id of idsOf(comment)) found.push([id, { kind: 'py-test', ref, test: comment, ...(/\bstopgap\b/i.test(comment) && { partial: true }) }]);
  }
  return found;
}

/**
 * The Python files that a CI workflow command runs: `python3 [-B] <file>.py` (a job that checks the repository out under
 * zplc/ names it from there), and `python3 [-B] -m unittest discover -s <dir> -p <glob>` (the top level of <dir>).
 */
export function pythonFilesRunInCi(files: string[], workflows: string[]): Set<string> {
  const runs = new Set<string>();
  const text = workflows.join('\n');
  for (const [, file = ''] of text.matchAll(/python3?(?:\s+-[A-Za-z])*\s+((?:[\w.-]+\/)*[\w.-]+\.py)\b/g)) runs.add(file.replace(/^zplc\//, ''));
  for (const [, dir = '', , glob = ''] of text.matchAll(/-m unittest discover\s+-s\s+(\S+)\s+-p\s+(['"]?)([^'"\s]+)\2/g)) {
    const pattern = new Bun.Glob(`${dir.replace(/\/$/, '')}/${glob}`);
    for (const file of files) if (pattern.match(file) && !file.slice(dir.length + 1).includes('/')) runs.add(file);
  }
  return new Set(files.filter((file) => runs.has(file)));
}

/** One journey declaration, on one line or laid out over several by a formatter, with either quote. */
export const JOURNEY_DECLARATION = /name: (['"])(.+?)\1,\s*example: (['"])[^'"]*\3,\s*proves: \[([^\]]*)\],\s*partly: \[([^\]]*)\]/g;

export function journeyChecks(ref: string, text: string): Array<[string, Check]> {
  const found: Array<[string, Check]> = [];
  for (const [, , name = '', , proves = '', partly = ''] of text.matchAll(JOURNEY_DECLARATION)) {
    for (const id of idsOf(proves)) found.push([id, { kind: 'journey', ref, test: name }]);
    for (const id of idsOf(partly)) found.push([id, { kind: 'journey', ref, test: name, partial: true }]);
  }
  return found;
}

/** The scanned checks of every tracked file that counts. */
export function scanFiles(files: string[], read: (file: string) => string, inventory: Inventory, prefixes?: Set<string>, pythonRuns: Set<string> = new Set()): Array<[string, Check]> {
  const rules = [...inventory.runs, ...inventory.notRunInCi].map((rule) => ({ glob: new Bun.Glob(rule.pattern), runs: 'job' in rule }));
  const runsInCi = (file: string) => rules.find(({ glob }) => glob.match(file))?.runs === true;
  const found: Array<[string, Check]> = [];
  for (const file of files) {
    if (/^conformance\/.*\.expect\.json$/.test(file)) found.push(...conformanceChecks(file, read(file)));
    else if (pythonRuns.has(file)) found.push(...pythonChecks(file, read(file)));
    else if (file === JOURNEYS) found.push(...journeyChecks(file, read(file)));
    else if (TEST_FILE.test(file) && runsInCi(file)) {
      if (/\.test\.(ts|tsx|mjs)$/.test(file)) found.push(...unitChecks(file, read(file)));
      else if (file.endsWith('.c')) found.push(...cChecks(file, read(file)));
    }
  }
  return prefixes ? found.filter(([id]) => prefixes.has(id.slice(0, id.indexOf('-')))) : found;
}

// ---------------------------------------------------------------------------------------------------------------------
// The record
// ---------------------------------------------------------------------------------------------------------------------

const keyOf = (id: string, check: Check) => `${id}|${check.kind}|${check.ref}|${check.test ?? ''}`;

/** Scanned checks, with a hand-written record replacing the scanned one it names, and every other hand-written record kept. */
export function mergeEvidence(scanned: Array<[string, Check]>, hand: Evidence): Evidence {
  const written = new Set(Object.entries(hand).flatMap(([id, checks]) => checks.map((check) => keyOf(id, check))));
  const merged: Evidence = {};
  const seen = new Set<string>();
  const add = (id: string, check: Check) => {
    if (seen.has(keyOf(id, check))) return;
    seen.add(keyOf(id, check));
    (merged[id] ??= []).push(check);
  };
  for (const [id, check] of scanned) if (!written.has(keyOf(id, check))) add(id, check);
  for (const [id, checks] of Object.entries(hand)) for (const check of checks) add(id, check);
  return merged;
}

/** Hand-written records of a recorded evidence file: the ones that carry a note. */
export function handWritten(evidence: Evidence): Evidence {
  const kept: Evidence = {};
  for (const [id, checks] of Object.entries(evidence)) {
    const own = checks.filter((check) => check.note !== undefined);
    if (own.length > 0) kept[id] = own;
  }
  return kept;
}

/** Code-point order, so that the committed file does not depend on the locale of the machine that writes it. */
const compare = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);

/** One check per line, requirements in the order of the index, so that a new check shows as one added line. */
export function serializeEvidence(evidence: Evidence, order: string[]): string {
  const rank = new Map(order.map((id, position) => [id, position]));
  const ids = Object.keys(evidence).sort((a, b) => (rank.get(a) ?? Infinity) - (rank.get(b) ?? Infinity) || compare(a, b));
  const byKind = (a: Check, b: Check) => KINDS.indexOf(a.kind) - KINDS.indexOf(b.kind) || compare(a.ref, b.ref) || compare(a.test ?? '', b.test ?? '');
  const entries = ids.map((id) => `  ${JSON.stringify(id)}: [\n${[...evidence[id]!].sort(byKind).map((check) => `    ${JSON.stringify(check)}`).join(',\n')}\n  ]`);
  return `{\n${entries.join(',\n')}\n}\n`;
}

