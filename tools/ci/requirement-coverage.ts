/** `listed` holds the ids of the expected-failure list: "<file> > <describe> > <test>". */
export function isFailing(check: Check, listed: string[]): boolean {
  const file = check.kind === 'conformance' ? CONFORMANCE_RUNNER : check.ref;
  return listed.some((id) => {
    const [head, ...rest] = id.split(' > ');
    return head === file && check.test !== undefined && rest.includes(check.test);
  });
}

export function coverage(index: Array<Pick<Requirement, 'id' | 'workstream' | 'title'>>, evidence: Evidence, listed: string[]) {
  const known = new Set(index.map((entry) => entry.id));
  const errors = Object.keys(evidence).filter((id) => !known.has(id)).map((id) => `evidence names ${id}, which is not in tools/ci/requirements-index.json`);
  const states = new Map<string, State>();
  const kinds = new Map<string, Kind[]>();
  /** Covered requirements that still have a check on the expected-failure list: covered, but not yet green. */
  const withFailures: string[] = [];
  /** Requirements held by a gate record: never covered, whatever their checks. */
  const gated: string[] = [];
  const empty = (): Counts => ({ total: 0, covered: 0, partial: 0, decided: 0, uncovered: 0 });
  const overall = empty();
  const byWorkstream: Record<string, Counts> = {};
  for (const { id, workstream } of index) {
    const all = evidence[id] ?? [];
    const checks = all.filter((check) => check.kind !== 'gate');
    if (checks.length < all.length) gated.push(id);
    const passing = checks.length < all.length ? [] : checks.filter((check) => check.kind !== 'decided' && !check.partial && !isFailing(check, listed));
    const decided = checks.some((check) => check.kind === 'decided');
    const state: State = passing.length > 0 ? 'covered' : decided ? 'decided' : checks.length > 0 ? 'partial' : 'uncovered';
    states.set(id, state);
    kinds.set(id, [...new Set(passing.map((check) => check.kind))]);
    if (state === 'covered' && checks.some((check) => isFailing(check, listed))) withFailures.push(id);
    for (const counts of [overall, (byWorkstream[workstream] ??= empty())]) {
      counts.total++;
      counts[state]++;
    }
  }
  return { overall, byWorkstream, states, kinds, withFailures, gated, errors };
}

/** Owning packages ranked by how many of their requirements have no passing complete check. */
export function groups(index: Requirement[], states: Map<string, State>) {
  const byPackage = new Map<string, { workPackage: string; phase: number | undefined; uncovered: string[]; partial: string[]; total: number }>();
  for (const { id, workPackage = 'none', phase } of index) {
    const group = byPackage.get(workPackage) ?? { workPackage, phase, uncovered: [], partial: [], total: 0 };
    group.total++;
    const state = states.get(id);
    if (state === 'uncovered') group.uncovered.push(id);
    if (state === 'partial') group.partial.push(id);
    byPackage.set(workPackage, group);
  }
  return [...byPackage.values()].filter((group) => group.uncovered.length + group.partial.length > 0)
    .sort((a, b) => b.uncovered.length + b.partial.length - (a.uncovered.length + a.partial.length) || a.workPackage.localeCompare(b.workPackage, 'en', { numeric: true }));
}

// ---------------------------------------------------------------------------------------------------------------------
// The tracked tree
// ---------------------------------------------------------------------------------------------------------------------

function load() {
  const read = (file: string) => readFileSync(new URL(file, ROOT), 'utf8');
  const tracked = Bun.spawnSync(['git', 'ls-files'], { cwd: ROOT.pathname });
  if (tracked.exitCode !== 0) throw new Error(`git ls-files failed: ${tracked.stderr.toString()}`);
  const files = tracked.stdout.toString().split('\n').filter(Boolean);
  const index = JSON.parse(read('tools/ci/requirements-index.json')) as Requirement[];
  const indexErrors = validateIndex(index);
  if (indexErrors.length > 0) throw new Error(`requirements-index.json is not well formed: ${indexErrors[0]}`);
  const inventory = JSON.parse(read('tools/ci/test-inventory.json')) as Inventory;
  const entries = JSON.parse(read('tools/ci/expected-failures.json')) as Array<{ test: string }>;
  const gaps = /KNOWN_GAPS[^=]*=\s*\{([^}]*)\}/.exec(read(RUN_JOURNEYS))?.[1] ?? '';
  const knownGaps = [...gaps.matchAll(/(['"])(.+?)\1\s*:/g)].map((match) => `${JOURNEYS} > ${match[2]}`);
  const recorded = JSON.parse(read('tools/ci/requirement-evidence.json')) as Evidence;
  const prefixes = new Set(index.map((entry) => entry.workstream));
  const workflows = files.filter((file) => /^\.github\/workflows\/[^/]+\.ya?ml$/.test(file)).map(read);
  const evidence = mergeEvidence(scanFiles(files, read, inventory, prefixes, pythonFilesRunInCi(files, workflows)), handWritten(recorded));
  return { index, evidence, recorded, listed: [...entries.map((entry) => entry.test), ...knownGaps] };
}

/** For the CI summary: the counts, the errors that must turn a job red, and the line to print. */
export function progress() {
  const { index, evidence, listed } = load();
  const { overall, gated, errors } = coverage(index, evidence, listed);
  return { overall, errors, line: `requirements: ${overall.covered} of ${overall.total} covered by an executed check, ${overall.partial} partial, ${overall.decided} decided, ${overall.uncovered} uncovered, ${gated.length} gated on evidence no test gives` };
}

