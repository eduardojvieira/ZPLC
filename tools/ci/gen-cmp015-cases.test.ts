// The 64-bit and LREAL conformance cases (conformance/cmp/cmp-015-*) are written by tools/ci/gen_cmp015_cases.py from
// values computed in Python. A case edited by hand, or a generator edited without writing the cases, fails here.
import { describe, expect, test } from 'bun:test';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));

describe('the cases of CMP-015 generated by tools/ci/gen_cmp015_cases.py', () => {
  test('are what the generator writes', () => {
    const result = spawnSync('python3', ['-B', 'tools/ci/gen_cmp015_cases.py', '--check'], { cwd: root, encoding: 'utf8' });
    expect(result.stderr).toBe('');
    expect(result.status).toBe(0);
  });
});
