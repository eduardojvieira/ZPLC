// The list of error codes that the main process reads is the registry of the compiler (CMP-006).
import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'bun:test';

import { ERROR_CODES } from '../../packages/zplc-compiler/src/compiler/error-codes';
import { ERROR_CODE_MIRROR, isMirroredErrorCode } from '../../packages/zplc-ide/electron/errorCodes.generated';
import { MIRROR_FILE, renderMirror } from './generate-error-codes';

describe('the generated list of error codes (CMP-006)', () => {
  it('is the registry of the compiler, in its order', () => {
    expect([...ERROR_CODE_MIRROR]).toEqual([...ERROR_CODES]);
    expect(readFileSync(MIRROR_FILE, 'utf8')).toBe(renderMirror());
  });

  it('answers membership', () => {
    expect(isMirroredErrorCode('UNKNOWN_IDENTIFIER')).toBe(true);
    expect(isMirroredErrorCode('COMPILATION_FAILED')).toBe(false);
    expect(isMirroredErrorCode(7)).toBe(false);
  });

  it('is written by the generator for a list it is given', () => {
    const text = renderMirror(['A_CODE', 'ANOTHER_CODE']);
    expect(text).toContain("  'A_CODE',\n  'ANOTHER_CODE',\n];");
    expect(text).toContain('GENERATED by tools/ci/generate-error-codes.ts');
  });
});
